#!/usr/bin/env python3
"""generate_docs.py — regenerate docs/generated/source-tree.md from the source tree.

Walks src/ and qml/, and for every .h/.cpp/.qml file extracts a short description
from that file's own banner comment, e.g.:

    // ── AccountController ─────────────────────────────────────────────
    //
    // Session-wide source of truth for the accounts list — backs ...

or the shorter one-line-banner form:

    // ── PillButton ────────────────────────────────────────────────────
    // The big colored action button used everywhere ...

This is the convention already used throughout this codebase (see any header
comment in src/ or qml/) — this script does not require adding anything new to
files that already follow it. A file with no banner comment is still listed,
just without a description, so the generated tree stays complete even before
every file has one.

Usage:
    python tools/generate_docs.py
    python tools/generate_docs.py --check   # exit 1 if the output would change
                                             # (wire into CI / a pre-commit hook)

Output: docs/generated/source-tree.md — regenerate this after adding, removing,
or renaming files under src/ or qml/. See docs/automated-docs.md for the full
convention and how to extend this script.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCAN_DIRS = ["src", "qml"]
EXTENSIONS = {".h", ".hpp", ".cpp", ".qml"}
OUTPUT_FILE = REPO_ROOT / "docs" / "generated" / "source-tree.md"

# Matches a banner rule line: // ── Name ──────────────── (dash run of any length)
BANNER_RULE_RE = re.compile(r"^//\s*[─\-]{2,}\s*(.+?)\s*[─\-]{2,}\s*$")
# A one-line banner with no trailing dashes: // ── Name
BANNER_NO_TRAIL_RE = re.compile(r"^//\s*[─\-]{2,}\s*(.+?)\s*$")
COMMENT_LINE_RE = re.compile(r"^//\s?(.*)$")

MAX_DESCRIPTION_CHARS = 320


@dataclass
class FileDoc:
    path: Path
    banner_name: str | None
    description: str | None


def extract_doc(path: Path) -> FileDoc:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return FileDoc(path, None, None)

    banner_name: str | None = None
    banner_idx: int | None = None

    for i, line in enumerate(lines[:60]):  # banners always live near the top
        m = BANNER_RULE_RE.match(line) or BANNER_NO_TRAIL_RE.match(line)
        if m:
            banner_name = m.group(1).strip(" ─-")
            banner_idx = i
            break

    if banner_idx is None:
        return FileDoc(path, None, None)

    # Collect description lines immediately after the banner: either a blank
    # `//` separator line then a paragraph, or the description directly below
    # the banner line (one-line-banner form). Stop at the first non-comment
    # line or the second blank comment line (paragraph break).
    desc_lines: list[str] = []
    blank_comment_seen = False
    for line in lines[banner_idx + 1 : banner_idx + 40]:
        m = COMMENT_LINE_RE.match(line)
        if not m:
            break
        text = m.group(1).rstrip()
        if not text:
            if desc_lines:
                break  # end of first paragraph
            blank_comment_seen = True
            continue
        if set(text) <= {"─", "-"}:
            continue  # a second rule line (closing banner), ignore
        desc_lines.append(text)

    description = " ".join(desc_lines).strip() or None
    if description and len(description) > MAX_DESCRIPTION_CHARS:
        description = description[: MAX_DESCRIPTION_CHARS - 1].rstrip() + "…"

    return FileDoc(path, banner_name, description)


def collect_files() -> list[Path]:
    files: list[Path] = []
    for scan_dir in SCAN_DIRS:
        base = REPO_ROOT / scan_dir
        if not base.exists():
            continue
        for path in sorted(base.rglob("*")):
            if path.is_file() and path.suffix in EXTENSIONS:
                files.append(path)
    return files


def render_markdown(docs: list[FileDoc]) -> str:
    out: list[str] = []
    out.append("# Generated Source Tree")
    out.append("")
    out.append(
        "> **Auto-generated by `tools/generate_docs.py` — do not edit by hand.**\n"
        "> Regenerate after adding, removing, or renaming a file under `src/` or `qml/`:\n"
        "> `python tools/generate_docs.py`. See `docs/automated-docs.md`."
    )
    out.append("")

    by_dir: dict[Path, list[FileDoc]] = {}
    for doc in docs:
        by_dir.setdefault(doc.path.parent, []).append(doc)

    for directory in sorted(by_dir, key=lambda p: p.relative_to(REPO_ROOT).as_posix()):
        rel_dir = directory.relative_to(REPO_ROOT).as_posix()
        out.append(f"## `{rel_dir}/`")
        out.append("")
        for doc in sorted(by_dir[directory], key=lambda d: d.path.name):
            name = doc.path.name
            if doc.description:
                out.append(f"- **`{name}`** — {doc.description}")
            elif doc.banner_name:
                out.append(f"- **`{name}`** — *(banner found, no description text)*")
            else:
                out.append(f"- `{name}` — *(no banner comment yet — see docs/automated-docs.md)*")
        out.append("")

    total = len(docs)
    documented = sum(1 for d in docs if d.description)
    out.append("---")
    out.append("")
    out.append(f"{documented}/{total} files have a description pulled from their banner comment.")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Don't write the file; exit 1 if the generated content would differ from what's on disk.",
    )
    args = parser.parse_args()

    files = collect_files()
    docs = [extract_doc(f) for f in files]
    content = render_markdown(docs)

    if args.check:
        existing = OUTPUT_FILE.read_text(encoding="utf-8") if OUTPUT_FILE.exists() else ""
        if existing != content:
            print(f"{OUTPUT_FILE} is stale — run: python tools/generate_docs.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT_FILE} is up to date.")
        return 0

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT_FILE} ({len(files)} files scanned, {sum(1 for d in docs if d.description)} with descriptions).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
